import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const Babel=require('../tools/vendor/babel-7.23.5.cjs');
const check=process.argv.includes('--check');
for(const name of ['accounting','crm']){
 const input=await readFile('src/'+name+'.jsx','utf8');
 const output='/* Generated by npm run build; edit src/'+name+'.jsx. */\n'+Babel.transform(input,{presets:['react'],sourceType:'script',comments:true,compact:false}).code+'\n';
 if(check)assert.equal(await readFile('public/'+name+'/app.js','utf8'),output,'Generated frontend is stale: '+name);
 else await writeFile('public/'+name+'/app.js',output);
}
console.log(check?'PASS production JS matches JSX sources; no browser Babel compilation':'Built accounting and CRM production JS');
